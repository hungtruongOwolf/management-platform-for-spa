// Sanity checks for the committed API contract: apps/api/openapi.json and the TS client generated
// from it. An interrupted `pnpm api:spec` used to leave openapi.json empty (shell redirection
// truncates before cargo finishes) and that got committed. These checks are cheap (no build), so
// the merge gate runs them first, and `scripts/api-spec.mjs` uses them before replacing the file.
//
//   node scripts/contract-files.mjs   → exit 1 with a reason when either file is broken
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export const OPENAPI_PATH = "apps/api/openapi.json";
export const SCHEMA_PATH = "packages/api-client/src/schema.ts";

/** Returns a reason the text is not a usable OpenAPI document, or null when it is. */
export function openApiProblem(text) {
  if (!text.trim()) return "empty";
  let doc;
  try {
    doc = JSON.parse(text);
  } catch (error) {
    return `not valid JSON (${error.message})`;
  }
  if (typeof doc !== "object" || doc === null || Array.isArray(doc)) return "not a JSON object";
  if (typeof doc.openapi !== "string") return 'missing the "openapi" version field';
  if (typeof doc.paths !== "object" || doc.paths === null || Object.keys(doc.paths).length === 0) {
    return 'has no "paths"';
  }
  return null;
}

/** Returns a reason the text is not a usable openapi-typescript output, or null when it is. */
export function schemaProblem(text) {
  if (!text.trim()) return "empty";
  for (const marker of ["export interface paths", "export interface components", "export interface operations"]) {
    if (!text.includes(marker)) return `missing \`${marker}\` (truncated or not generated by openapi-typescript)`;
  }
  return null;
}

function readOrNull(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

function main() {
  const problems = [];
  const spec = readOrNull(OPENAPI_PATH);
  const specProblem = spec === null ? "missing" : openApiProblem(spec);
  if (specProblem) problems.push(`${OPENAPI_PATH}: ${specProblem}`);
  const schema = readOrNull(SCHEMA_PATH);
  const tsProblem = schema === null ? "missing" : schemaProblem(schema);
  if (tsProblem) problems.push(`${SCHEMA_PATH}: ${tsProblem}`);
  if (problems.length > 0) {
    for (const problem of problems) console.error(`✗ ${problem}`);
    console.error("  regenerate with `pnpm api:gen` and commit both files");
    process.exit(1);
  }
  console.log("✓ contract files present and parseable");
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
